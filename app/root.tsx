export default function App() {
  return (
    <Providers>
      <Outlet />
    </Providers>
  );
}

export function ErrorBoundary({ error }: Route.ErrorBoundaryProps) {
  let message = "Something broke";
  let details = "An unexpected error occurred.";
  let stack: string | undefined;

  if (isRouteErrorResponse(error)) {
    message = error.status === 404 ? "404" : "Error";
    details =
      error.status === 404 ? "That page is not on this chain." : error.statusText || details;
  } else if (import.meta.env.DEV && error && error instanceof Error) {
    details = error.message;
    stack = error.stack;
  }

  return (
    <main className="mx-auto max-w-xl px-6 py-20">
      <h1 className="brand text-4xl">{message}</h1>
      <p className="mt-3 text-fog">{details}</p>
      {stack && (
        <pre className="mt-6 overflow-x-auto rounded-lg border border-line bg-panel p-4 text-xs">
          <code>{stack}</code>
        </pre>
      )}
    </main>
  );
}
